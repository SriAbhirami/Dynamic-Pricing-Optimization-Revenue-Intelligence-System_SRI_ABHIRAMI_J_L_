@router.get(
    "/seasonal/{product_id}",
    response_model=SeasonalTrendResponse
)
def get_seasonal_trend(
    product_id: str,
    db: Session = Depends(get_db)
):

    try:

        # ====================================================
        # GET HISTORICAL MONTHLY DEMAND
        # ====================================================

        monthly_data = (

            db.query(

                func.extract(
                    "month",
                    PricingDemand.date
                ).label("month_number"),

                func.avg(
                    PricingDemand.demand_index
                ).label("average_demand")

            )

            .filter(
                PricingDemand.product_id ==
                str(product_id)
            )

            .filter(
                PricingDemand.date.isnot(None)
            )

            .filter(
                PricingDemand.demand_index.isnot(None)
            )

            .group_by(

                func.extract(
                    "month",
                    PricingDemand.date
                )

            )

            .order_by(

                func.extract(
                    "month",
                    PricingDemand.date
                )

            )

            .all()

        )


        # ====================================================
        # NO DATA
        # ====================================================

        if not monthly_data:

            raise HTTPException(

                status_code=404,

                detail=(
                    f"No historical demand data found "
                    f"for product {product_id}."
                )

            )


        # ====================================================
        # FORMAT MONTHLY DATA
        # ====================================================

        seasonal_data = []


        for row in monthly_data:

            month_number = int(
                row.month_number
            )

            average_demand = float(
                row.average_demand or 0
            )


            seasonal_data.append({

                "month":
                    MONTH_NAMES.get(
                        month_number,
                        f"Month {month_number}"
                    ),

                "month_number":
                    month_number,

                "demand":
                    round(
                        average_demand,
                        2
                    )

            })


        # ====================================================
        # PEAK MONTH
        # ====================================================

        peak_point = max(

            seasonal_data,

            key=lambda item:
                item["demand"]

        )


        # ====================================================
        # LOWEST MONTH
        # ====================================================

        lowest_point = min(

            seasonal_data,

            key=lambda item:
                item["demand"]

        )


        peak_demand = float(
            peak_point["demand"]
        )

        lowest_demand = float(
            lowest_point["demand"]
        )


        # ====================================================
        # SEASONALITY CHANGE
        # ====================================================

        if lowest_demand > 0:

            seasonality_change_pct = (

                (
                    peak_demand -
                    lowest_demand
                )
                /
                lowest_demand

            ) * 100

        else:

            seasonality_change_pct = 0


        seasonality_change_pct = round(
            seasonality_change_pct,
            2
        )


        # ====================================================
        # SEASONALITY STRENGTH
        # ====================================================

        if seasonality_change_pct >= 40:

            seasonality_strength = "Strong"

        elif seasonality_change_pct >= 20:

            seasonality_strength = "Moderate"

        elif seasonality_change_pct >= 10:

            seasonality_strength = "Mild"

        else:

            seasonality_strength = "Stable"


        # ====================================================
        # RESPONSE
        # ====================================================

        return {

            "product_id":
                str(product_id),

            "seasonal_data":
                seasonal_data,

            "peak_month":
                peak_point["month"],

            "peak_demand":
                round(
                    peak_demand,
                    2
                ),

            "lowest_month":
                lowest_point["month"],

            "lowest_demand":
                round(
                    lowest_demand,
                    2
                ),

            "seasonality_strength":
                seasonality_strength,

            "seasonality_change_pct":
                seasonality_change_pct

        }


    except HTTPException:

        raise


    except Exception as e:

        raise HTTPException(

            status_code=500,

            detail=(
                f"Seasonal trend analysis failed: "
                f"{str(e)}"
            )

        )