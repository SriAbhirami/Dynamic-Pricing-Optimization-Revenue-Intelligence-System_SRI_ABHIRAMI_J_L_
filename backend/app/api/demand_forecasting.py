@router.post(
    "/predict",
    response_model=DemandForecastResponse
)
def predict_demand_index(
    data: DemandForecastRequest
):

    try:

        prediction = predict_demand(
            data.model_dump()
        )

        return {

            "predicted_demand_index":
                round(
                    float(prediction),
                    2
                )

        }

    except Exception as e:

        raise HTTPException(

            status_code=500,

            detail=(
                f"Demand prediction failed: {str(e)}"
            )

        )


